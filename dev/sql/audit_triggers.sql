-- ─────────────────────────────────────────────────────────────────────────────
-- 4. ROW LEVEL SECURITY (RLS)
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;

-- Leitura: apenas super-admins
DROP POLICY IF EXISTS "audit_logs: leitura apenas super admin" ON public.audit_logs;
CREATE POLICY "audit_logs: leitura apenas super admin"
  ON public.audit_logs FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.uuid = (CURRENT_SETTING('request.jwt.claims')::JSON)->>'sub'::TEXT
        AND u.is_admin_super = TRUE
    )
  );

-- Bloquear inserts/updates/deletes diretos via API (apenas triggers devem escrever)
DROP POLICY IF EXISTS "audit_logs: sem escrita direta" ON public.audit_logs;
CREATE POLICY "audit_logs: sem escrita direta"
  ON public.audit_logs FOR ALL
  TO authenticated
  USING (FALSE)
  WITH CHECK (FALSE);


-- ─────────────────────────────────────────────────────────────────────────────
-- 5. VIEW: v_audit_logs (facilita consultas com dados do usuário)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE VIEW public.v_audit_logs AS
SELECT
  l.id,
  l.created_date,
  l.user_uuid,
  u.name_full   AS user_name,
  u.email        AS user_email,
  l.table_name,
  l.operation,
  l.data_old,
  l.data_new,
  l.user_id
FROM public.audit_logs l
LEFT JOIN public.users u ON u.uuid = l.user_uuid::TEXT
ORDER BY l.created_date DESC;

COMMENT ON VIEW public.v_audit_logs IS 'View de auditoria com dados do usuário';


