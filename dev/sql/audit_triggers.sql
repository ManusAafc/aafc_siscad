-- ─────────────────────────────────────────────────────────────────────────────
-- 1. TABELA: audit_logs (Registro de auditoria)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_date  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'utc'::TEXT),
  user_uuid     UUID NULL,
  table_name    TEXT NULL,
  operation     TEXT NULL,
  data_old      JSONB NULL,
  data_new      JSONB NULL,
  user_id       BIGINT NULL,
  CONSTRAINT audit_logs_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_date   ON public.audit_logs (created_date DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_table_name     ON public.audit_logs (table_name);
CREATE INDEX IF NOT EXISTS idx_audit_logs_operation      ON public.audit_logs (operation);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_uuid      ON public.audit_logs (user_uuid);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id        ON public.audit_logs (user_id);

COMMENT ON TABLE  public.audit_logs            IS 'Auditoria de operações INSERT/UPDATE/DELETE nas tabelas do sistema';
COMMENT ON COLUMN public.audit_logs.created_date IS 'Data/hora da operação (UTC)';
COMMENT ON COLUMN public.audit_logs.user_uuid   IS 'UUID do usuário Supabase Auth que realizou a operação';
COMMENT ON COLUMN public.audit_logs.table_name  IS 'Nome da tabela afetada';
COMMENT ON COLUMN public.audit_logs.operation   IS 'Tipo da operação: INSERT, UPDATE ou DELETE';
COMMENT ON COLUMN public.audit_logs.data_old    IS 'Dados anteriores à operação (JSONB) — nulo para INSERT';
COMMENT ON COLUMN public.audit_logs.data_new    IS 'Dados posteriores à operação (JSONB) — nulo para DELETE';
COMMENT ON COLUMN public.audit_logs.user_id     IS 'ID numérico do usuário na tabela users';


-- ─────────────────────────────────────────────────────────────────────────────
-- 2. FUNÇÃO: fn_audit() — trigger genérico de auditoria
-- ─────────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_uuid UUID;
  v_user_id   BIGINT;
BEGIN
  -- Extrair UUID do usuário a partir do JWT (Supabase Auth)
  BEGIN
    v_user_uuid := (CURRENT_SETTING('request.jwt.claims')::JSON)->>'sub';
  EXCEPTION WHEN OTHERS THEN
    v_user_uuid := NULL;
  END;

  -- Buscar o ID numérico do usuário na tabela users
  IF v_user_uuid IS NOT NULL THEN
    SELECT id INTO v_user_id
    FROM public.users
    WHERE uuid = v_user_uuid::TEXT
    LIMIT 1;
  END IF;

  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.audit_logs (user_uuid, table_name, operation, data_old, data_new, user_id)
    VALUES (v_user_uuid, TG_TABLE_NAME, 'INSERT', NULL, TO_JSONB(NEW), v_user_id);
    RETURN NEW;

  ELSIF TG_OP = 'UPDATE' THEN
    -- So insere log se os dados realmente mudaram
    IF TO_JSONB(OLD) IS DISTINCT FROM TO_JSONB(NEW) THEN
      INSERT INTO public.audit_logs (user_uuid, table_name, operation, data_old, data_new, user_id)
      VALUES (v_user_uuid, TG_TABLE_NAME, 'UPDATE', TO_JSONB(OLD), TO_JSONB(NEW), v_user_id);
    END IF;
    RETURN NEW;

  ELSIF TG_OP = 'DELETE' THEN
    INSERT INTO public.audit_logs (user_uuid, table_name, operation, data_old, data_new, user_id)
    VALUES (v_user_uuid, TG_TABLE_NAME, 'DELETE', TO_JSONB(OLD), NULL, v_user_id);
    RETURN OLD;
  END IF;

  RETURN NULL;
END;
$$;


-- ─────────────────────────────────────────────────────────────────────────────
